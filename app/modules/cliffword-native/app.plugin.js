/**
 * Config plugin of the cliffword-native module: keeps the language model and the learner's photo
 * out of Android backups.
 *
 * The model (1.1 GB) lives in the app's files directory, files/models/ (expo-file-system's
 * document directory). Android Auto Backup includes that directory by default, and a backup over
 * the 25 MB quota is not uploaded at all, so the model would also stop the learner's database
 * from being backed up. The learner's photo for their picture in the story (files/avatar/,
 * src/adapters/photo) stays on the phone: it is never uploaded, backups included. These rules
 * exclude both folders from cloud backup (Android 6 to 11: android:fullBackupContent; 12 and
 * later: android:dataExtractionRules) and from device-to-device transfer; everything else is
 * backed up as before. The model is downloaded again after a restore; a restored app whose photo
 * is gone shows the default character. iOS needs no plugin: the module sets isExcludedFromBackup
 * on the files themselves.
 *
 * Use in app.json: "plugins": [..., "./modules/cliffword-native/app.plugin.js"]
 */
const fs = require('fs');
const path = require('path');
const { AndroidConfig, createRunOncePlugin, withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const MODELS_PATH = 'models/';
const PHOTO_PATH = 'avatar/';
/** The folders left out of backups, as exclude rules indented for the XML below. */
const excludes = (indent) =>
  [MODELS_PATH, PHOTO_PATH].map((p) => `${indent}<exclude domain="file" path="${p}" />`).join('\n');
const FULL_BACKUP_RULES = 'cliffword_backup_rules';
const DATA_EXTRACTION_RULES = 'cliffword_data_extraction_rules';

const fullBackupXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by modules/cliffword-native/app.plugin.js: the downloaded language model and the learner's photo stay out of backups. -->
<full-backup-content>
${excludes('  ')}
</full-backup-content>
`;

const dataExtractionXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by modules/cliffword-native/app.plugin.js: the downloaded language model and the learner's photo stay out of backups. -->
<data-extraction-rules>
  <cloud-backup>
${excludes('    ')}
  </cloud-backup>
  <device-transfer>
${excludes('    ')}
  </device-transfer>
</data-extraction-rules>
`;

function withBackupRuleFiles(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const xmlDir = path.join(await AndroidConfig.Paths.getResourceFolderAsync(cfg.modRequest.projectRoot), 'xml');
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(path.join(xmlDir, `${FULL_BACKUP_RULES}.xml`), fullBackupXml);
      fs.writeFileSync(path.join(xmlDir, `${DATA_EXTRACTION_RULES}.xml`), dataExtractionXml);
      return cfg;
    },
  ]);
}

function withBackupRuleAttributes(config) {
  return withAndroidManifest(config, (cfg) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    const existing = application.$['android:fullBackupContent'] || application.$['android:dataExtractionRules'];
    if (existing && !String(existing).includes('cliffword_')) {
      // Another plugin set its own rules; merging XML rule files is not attempted.
      throw new Error(
        `cliffword-native: android backup rules are already set (${existing}). Exclude files/models/ and files/avatar/ in those rules instead.`,
      );
    }
    application.$['android:fullBackupContent'] = `@xml/${FULL_BACKUP_RULES}`;
    application.$['android:dataExtractionRules'] = `@xml/${DATA_EXTRACTION_RULES}`;
    return cfg;
  });
}

function withCliffwordNative(config) {
  return withBackupRuleAttributes(withBackupRuleFiles(config));
}

module.exports = createRunOncePlugin(withCliffwordNative, 'cliffword-native', '1.0.0');
