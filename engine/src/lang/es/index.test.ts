import { describe, expect, it } from 'vitest';
import type { CorrectionRule, RegisterPack, SlangEntry } from '../types';
import { createMockModel } from '../../model/mock';
import { MOCK_CORPUS_ES } from '../../model/mockCorpus';
import { createSpanishPack, registerClips } from './index';

function slang(form: string, neutral: string, kind: SlangEntry['kind'] = 'clipped'): SlangEntry {
  return {
    form, norm: form.replace(/’/g, "'").toLowerCase(), neutral, lemma: form.toLowerCase(), gloss: { en: neutral },
    regions: ['CARIB'], formality: 'street', explicit: false, kind,
  };
}

const STUB_REGISTERS: RegisterPack[] = [
  {
    id: 'es-PR', region: 'PR',
    entries: [
      slang("'tá", 'está'), slang("pa'", 'para'), slang('janguear', 'salir', 'word'), slang('corillo', 'grupo', 'word'),
      slang("'cuchar", 'escuchar'), slang('brutal', 'excelente', 'word'),
    ],
  },
];

const STUB_RULES: CorrectionRule[] = [
  { kind: 'swap', id: 'ser-estar', explainKey: 'ser_estar', groups: [['soy', 'estoy'], ['es', 'está']] },
];

describe('createSpanishPack', () => {
  it('implements the LanguagePack contract with defaults', () => {
    const pack = createSpanishPack();
    expect(pack.code).toBe('es');
    expect(pack.rules).toEqual([]);
    expect(pack.registers).toEqual([]);
    expect(pack.normalize('¡Hola!')).toBe('hola');
    expect(pack.frequencyRank('el')).toBe(1);
    expect(pack.frequencyRank('janguear')).toBeUndefined();
    expect(pack.inflect('tener', { mood: 'ind', tense: 'pret', person: '3', number: 's' })).toBe('tuvo');
    expect(pack.analyze('tuvo')[0]?.lemma).toBe('tener');
    expect(pack.segment('Hola, Marta.').map((s) => s.kind)).toEqual(['word', 'punct', 'space', 'word', 'punct']);
  });

  it('passes rules and registers through', () => {
    const pack = createSpanishPack({ rules: STUB_RULES, registers: STUB_REGISTERS });
    expect(pack.rules).toBe(STUB_RULES);
    expect(pack.registers).toBe(STUB_REGISTERS);
  });

  it('with registers, clipped forms segment as words and analyze to slang lemmas', () => {
    const plain = createSpanishPack();
    const street = createSpanishPack({ registers: STUB_REGISTERS });
    const text = "'Cuchar el corillo";
    expect(plain.segment(text).filter((s) => s.kind === 'word').map((s) => s.text)).toEqual(['Cuchar', 'el', 'corillo']);
    const words = street.segment(text).filter((s) => s.kind === 'word');
    expect(words.map((s) => s.text)).toEqual(["'Cuchar", 'el', 'corillo']);
    expect(street.analyze(words[0]?.norm ?? '')[0]).toMatchObject({ lemma: "'cuchar", pos: 'VERB' });
    expect(street.analyze('corillo')[0]).toMatchObject({ lemma: 'corillo', pos: 'NOUN' });
    expect(plain.analyze('corillo')).toEqual([]);
  });

  it('a slang word that is also standard keeps the standard analysis first', () => {
    const street = createSpanishPack({ registers: STUB_REGISTERS });
    const a = street.analyze('brutal');
    expect(a[0]).toMatchObject({ lemma: 'brutal', pos: 'ADJ' });
  });

  it('registerClips finds apostrophe forms', () => {
    expect(registerClips(STUB_REGISTERS)).toEqual({ leading: ["'tá", "'tá", "'cuchar", "'cuchar"], trailing: ["pa'", "pa'"] });
    expect(registerClips([])).toEqual({ leading: [], trailing: [] });
  });
});

describe('pack against the mock model corpus', () => {
  const street = createSpanishPack({ registers: STUB_REGISTERS });
  const names = new Set(['marta']);

  it('analyzes every word of the mock corpus (names aside)', () => {
    const unknown: string[] = [];
    for (const sentence of MOCK_CORPUS_ES) {
      for (const s of street.segment(sentence)) {
        if (s.kind !== 'word' || names.has(s.norm)) continue;
        if (street.analyze(s.norm).length === 0) unknown.push(s.norm);
      }
    }
    expect(unknown).toEqual([]);
  });

  it('segments and analyzes sentences generated by the mock model', async () => {
    const model = createMockModel();
    const outs = await model.generate('Ayer', { n: 8, maxTokens: 12, temperature: 0.8, seed: 7 });
    let words = 0;
    let known = 0;
    for (const text of outs) {
      const segs = street.segment(text);
      expect(segs.map((s) => s.text).join('')).toBe(text);
      for (const s of segs) {
        if (s.kind !== 'word' || names.has(s.norm)) continue;
        words++;
        if (street.analyze(s.norm).length) known++;
      }
    }
    expect(words).toBeGreaterThan(20);
    expect(known).toBe(words);
  });

  it('every whole-word next-token candidate of the mock model is analyzable', async () => {
    const model = createMockModel();
    const cands = await model.nextTokens('Ella está', 15);
    const wordCands = cands
      .map((c) => c.text.trim())
      .filter((t) => /^\p{L}+$/u.test(t) && t.length <= 6 && !names.has(t.toLowerCase()));
    expect(wordCands.length).toBeGreaterThan(3);
    for (const w of wordCands) {
      // 4-letter first pieces of long words are not words; skip those that are prefixes only.
      const a = street.analyze(street.normalize(w));
      if (w.length === 4 && a.length === 0) continue;
      expect(a.length, w).toBeGreaterThan(0);
    }
  });
});
